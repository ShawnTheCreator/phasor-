# Grid-Effect Advisory Composer (Feature 12)
def generate_grid_advisory(
    g_scale_level: str,
    overall_tier: str,
    total_q_loss_mvar: float,
    ranked_substations: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """Auto-generates plain-language control-room operational bulletins under NERC TPL-007."""
    scale = NOAA_G_SCALES.get(g_scale_level, NOAA_G_SCALES["G0"])
    top_sub = ranked_substations[0] if ranked_substations else {"substation_name": "Grid-wide", "gic_neutral_amps": 0.0}

    bulletin_title = f"SPACE WEATHER ADVISORY: {scale['name'].upper()} ({g_scale_level}) IN PROGRESS"

    recommendations = []
    if overall_tier in ["WATCH", "CRITICAL"]:
        recommendations.append("Defer all non-essential 765 kV transmission line switching and maintenance outages.")
        recommendations.append(f"Place Static VAR Compensators at Perseus and Beta on manual high-gain voltage control (projected Q_loss: {total_q_loss_mvar:.1f} MVAR).")
        recommendations.append(f"Monitor neutral DC earthing currents on {top_sub['substation_name']} and Koeberg Nuclear GSU banks.")
        recommendations.append("Bring fast-response gas turbine / pumped storage reserves to hot standby for reactive margin stability.")
    elif overall_tier == "ADVISORY":
        recommendations.append("Notify National Transmission Control Centre (NTCC) dispatchers of geomagnetic storm onset.")
        recommendations.append("Log baseline transformer dissolved gas analysis (DGA) and winding top-oil temperatures.")
        recommendations.append("Verify operational status of series capacitors along the trans-Karoo backbone.")
    else:
        recommendations.append("Continue routine baseline space weather monitoring.")
        recommendations.append("Ground telemetry links to SANSA Hermanus and DSCOVR L1 are nominal.")

    return {
        "title": bulletin_title,
        "issued_by": "Phasor GridGuard Operations & Eskom NTCC Coordination Desk",
        "classification": "OPERATIONAL BULLETIN (NERC TPL-007 / SAPP Grid Code)",
        "g_scale": g_scale_level,
        "g_scale_name": scale["name"],
        "official_grid_effects": scale["grid_impact"],
        "lead_substation_at_risk": f"{top_sub['substation_name']} ({top_sub['gic_neutral_amps']} A)",
        "total_reactive_power_deficit_mvar": total_q_loss_mvar,
        "operational_recommendations": recommendations,
        "suggested_dispatch_recipients": [
            "eskom-ntcc-shift@eskom.co.za",
            "sansa-spaceweather@sansa.org.za",
            "sapp-coordination@sapp.co.zw"
        ]
    }


def assess_network_risk(
    gic_solution: Dict[str, Any],
    substations: Dict[str, Substation] = SUBSTATIONS
) -> Dict[str, Any]:
    """
    Evaluates system-wide grid risk profile from network GIC solution.
    """
    sub_risks: Dict[str, Dict[str, Any]] = {}
    tier_counts = {RiskTier.NORMAL: 0, RiskTier.ADVISORY: 0, RiskTier.WATCH: 0, RiskTier.CRITICAL: 0}
    total_q_loss_mvar = 0.0

    for sub_id, sub in substations.items():
        neutral_amps = gic_solution["substation_gic_neutral_amps"].get(sub_id, 0.0)
        risk_info = evaluate_substation_risk(sub, neutral_amps)
        sub_risks[sub_id] = risk_info
        tier_counts[risk_info["risk_tier"]] += 1
        total_q_loss_mvar += risk_info["q_loss_mvar"]

    # System-wide overall status
    if tier_counts[RiskTier.CRITICAL] > 0:
        overall_tier = RiskTier.CRITICAL
    elif tier_counts[RiskTier.WATCH] > 0:
        overall_tier = RiskTier.WATCH
    elif tier_counts[RiskTier.ADVISORY] > 0:
        overall_tier = RiskTier.ADVISORY
    else:
        overall_tier = RiskTier.NORMAL

    # Sort substations by highest absolute GIC
    ranked_substations = sorted(
        sub_risks.values(),
        key=lambda x: abs(x["gic_neutral_amps"]),
        reverse=True
    )

    return {
        "overall_grid_tier": overall_tier,
        "total_reactive_power_loss_mvar": round(total_q_loss_mvar, 2),
        "tier_counts": tier_counts,
        "ranked_substations": ranked_substations,
        "substation_details": sub_risks,
        "e_field": {
            "ex_v_km": round(gic_solution["ex_v_km"], 4),
            "ey_v_km": round(gic_solution["ey_v_km"], 4),
            "magnitude_v_km": round(gic_solution["e_magnitude_v_km"], 4)
        }
    }
