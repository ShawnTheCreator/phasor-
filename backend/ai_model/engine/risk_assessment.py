"""
Transformer Risk Assessment & Actionable Grid Mitigation Engine.

Translates raw GIC amplitudes into physical transformer impacts:
- Half-cycle quasi-DC core saturation
- Reactive power consumption (Q_loss in MVAR)
- Harmonic distortion risk (THD)
- Hot-spot tank heating & gas bubble formation
- Operational alert tiers and actionable operator mitigations
"""

from typing import Dict, Any, List
from engine.grid_topology import Substation, SUBSTATIONS


class RiskTier:
    NORMAL = "NORMAL"
    ADVISORY = "ADVISORY"
    WATCH = "WATCH"
    CRITICAL = "CRITICAL"


def evaluate_substation_risk(
    substation: Substation,
    gic_neutral_amps: float
) -> Dict[str, Any]:
    """
    Evaluates individual transformer risk at a substation.

    Args:
        substation: Substation object with topology metadata.
        gic_neutral_amps: Computed 3-phase neutral GIC in Amperes.

    Returns:
        Dictionary of physical indicators, risk tier, and mitigation actions.
    """
    abs_neutral = abs(gic_neutral_amps)
    amps_per_phase = abs_neutral / 3.0

    # 1. Reactive Power Loss (MVAR) estimation
    # Q_loss ~ k_q * V_pu * I_gic_phase (IEEE standard rule of thumb)
    # k_q is ~1.0 MVAR/Amp for 765kV/400kV autotransformers
    kq = 1.1 if substation.voltage_kv >= 765.0 else 0.85
    q_loss_mvar = kq * 1.0 * amps_per_phase

    # 2. Risk Tier Classification based on critical saturation threshold
    crit_thresh = substation.critical_threshold_amps
    if abs_neutral < 5.0:
        tier = RiskTier.NORMAL
        badge_color = "#10b981"  # Emerald green
        urgency = "Low"
        headline = "System operating within normal geomagnetic margins."
        action = "No immediate operational intervention required. Continue baseline monitoring."
    elif abs_neutral < 15.0:
        tier = RiskTier.ADVISORY
        badge_color = "#f59e0b"  # Amber
        urgency = "Moderate"
        headline = f"Elevated quasi-DC earthing current ({abs_neutral:.1f} A) detected."
        action = ("Monitor transformer dissolved gas analysis (DGA) and winding temperatures. "
                  "Defer scheduled corridor switching operations.")
    elif abs_neutral < crit_thresh:
        tier = RiskTier.WATCH
        badge_color = "#f97316"  # Orange
        urgency = "High"
        headline = f"Significant core saturation warning ({abs_neutral:.1f} A neutral GIC)."
        action = (f"Reactive power deficit of ~{q_loss_mvar:.1f} MVAR expected. "
                  "Engage static VAR compensators (SVCs) and capacitor banks; place generation on stand-by.")
    else:
        tier = RiskTier.CRITICAL
        badge_color = "#ef4444"  # Red
        urgency = "Severe"
        headline = f"CRITICAL GIC SATURATION ({abs_neutral:.1f} A) - THERMAL & VOLTAGE HAZARD!"
        action = (f"Severe half-cycle core saturation at {substation.name}. "
                  "Alert Eskom National Transmission Control Centre (NTCC). "
                  "Prepare to re-route high-voltage power flows and inspect transformer oil temperature.")

    # 3. Harmonics Risk Index (even and odd harmonics generated by saturation)
    harmonics_risk = min(100.0, (abs_neutral / crit_thresh) * 100.0)

    return {
        "substation_id": substation.id,
        "substation_name": substation.name,
        "province": substation.province,
        "voltage_kv": substation.voltage_kv,
        "gic_neutral_amps": round(gic_neutral_amps, 2),
        "gic_per_phase_amps": round(amps_per_phase, 2),
        "q_loss_mvar": round(q_loss_mvar, 2),
        "harmonics_risk_pct": round(harmonics_risk, 1),
        "risk_tier": tier,
        "badge_color": badge_color,
        "urgency": urgency,
        "headline": headline,
        "recommended_action": action,
    }


